package wynnphoton.gradle;

import com.euphoriapatches.shaderpatcher.PatchSpec;
import com.euphoriapatches.shaderpatcher.exception.ShaderPatcherException;
import com.euphoriapatches.shaderpatcher.generate.GenerateRequest;
import com.euphoriapatches.shaderpatcher.generate.GeneratedPatch;
import com.euphoriapatches.shaderpatcher.generate.PatchGenerator;
import com.wynnphoton.core.BundleFormat;
import org.gradle.api.DefaultTask;
import org.gradle.api.GradleException;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.file.RegularFileProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.InputDirectory;
import org.gradle.api.tasks.InputFile;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.PathSensitive;
import org.gradle.api.tasks.PathSensitivity;
import org.gradle.api.tasks.TaskAction;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.SortedMap;
import java.util.TreeMap;

/**
 * Builds the wynn_photon/ resource folder: the ShaderPatcher patch that turns the base pack into the patched pack, a
 * manifest, and the hashes the mod uses to recognise copies of the base pack in the shaderpacks folder.
 */
public abstract class GeneratePatchBundleTask extends DefaultTask {
	@InputDirectory
	@PathSensitive(PathSensitivity.RELATIVE)
	public abstract DirectoryProperty getBaseDir();

	/** The base pack as players have it. ShaderPatcher stores its fingerprint in the patch. */
	@InputFile
	@PathSensitive(PathSensitivity.NONE)
	public abstract RegularFileProperty getBaseZip();

	@InputDirectory
	@PathSensitive(PathSensitivity.RELATIVE)
	public abstract DirectoryProperty getPatchesDir();

	@Input
	public abstract Property<String> getPatchName();

	@Input
	public abstract Property<String> getModVersion();

	@Input
	public abstract Property<String> getBaseName();

	@Input
	public abstract Property<String> getBaseDisplayName();

	@OutputDirectory
	public abstract DirectoryProperty getOutputDir();

	@TaskAction
	public void generate() throws IOException {
		Path baseDir = getBaseDir().get().getAsFile().toPath();
		Path patchesDir = getPatchesDir().get().getAsFile().toPath();
		Path out = getOutputDir().get().getAsFile().toPath();
		FileTrees.deleteRecursively(out);

		// Fail the build if a patch no longer applies to the base pack.
		SortedMap<String, byte[]> patched;
		try {
			patched = FileTrees.patched(baseDir, patchesDir);
		} catch (IOException e) {
			throw new GradleException("A patch does not apply to " + getBaseDisplayName().get() + ": " + e.getMessage(), e);
		}

		SortedMap<String, byte[]> patches = FileTrees.patchFiles(patchesDir);
		StringBuilder patchSet = new StringBuilder();
		patches.forEach((path, content) -> patchSet.append(path).append('\n')
				.append(new String(content, StandardCharsets.UTF_8)).append('\0'));
		String patchSetHash = BundleFormat.sha256(patchSet.toString());

		SortedMap<String, String> fingerprint = new TreeMap<>();
		FileTrees.hashes(FileTrees.read(baseDir)).forEach((path, hash) -> {
			if (path.startsWith(BundleFormat.FINGERPRINT_PREFIX)) {
				fingerprint.put(path, hash);
			}
		});
		if (fingerprint.isEmpty()) {
			throw new GradleException("The base pack in " + baseDir + " has no " + BundleFormat.FINGERPRINT_PREFIX + " folder");
		}

		// The marker is part of the patched pack, so a pack never appears in the shaderpacks folder without it.
		// Written by hand: Properties.store adds the date, and the same patches should give the same patch.
		String marker = "# Created by the Wynn-Photon mod. It deletes and rebuilds this folder when its patches change.\n"
				+ BundleFormat.KEY_PATCH_NAME + "=" + getPatchName().get() + "\n"
				+ BundleFormat.KEY_MOD_VERSION + "=" + getModVersion().get() + "\n"
				+ BundleFormat.KEY_PATCH_SET_HASH + "=" + patchSetHash + "\n"
				+ "base=" + getBaseDisplayName().get() + "\n";
		patched.put(BundleFormat.MARKER_FILE, marker.getBytes(StandardCharsets.UTF_8));

		Path root = out.resolve(BundleFormat.ROOT);
		String manifest = "# Generated by generatePatchBundle\n"
				+ BundleFormat.KEY_PATCH_NAME + "=" + getPatchName().get() + "\n"
				+ BundleFormat.KEY_MOD_VERSION + "=" + getModVersion().get() + "\n"
				+ BundleFormat.KEY_BASE_NAME + "=" + getBaseName().get() + "\n"
				+ BundleFormat.KEY_BASE_DISPLAY_NAME + "=" + getBaseDisplayName().get() + "\n"
				+ BundleFormat.KEY_PATCH_SET_HASH + "=" + patchSetHash + "\n";
		FileTrees.writeString(out.resolve(BundleFormat.MANIFEST), manifest);
		FileTrees.writeString(out.resolve(BundleFormat.BASE_FILES), FileTrees.formatHashes(fingerprint));
		long patchSize = writePatch(patched, out.resolve(BundleFormat.PATCH_FILE));
		getLogger().lifecycle("Patch bundle: {} patch file(s) as a {} byte ShaderPatcher patch, {} base files fingerprinted under {}",
				patches.size(), patchSize, fingerprint.size(), root);
	}

	/**
	 * Has ShaderPatcher diff the base zip against the patched pack. Before it writes the patch, it applies it to the
	 * base and checks that the result is the patched pack, byte for byte.
	 */
	private long writePatch(SortedMap<String, byte[]> patched, Path patchFile) throws IOException {
		Path temp = getTemporaryDir().toPath();
		Path edited = temp.resolve("patched");
		Path generated = temp.resolve("patch");
		FileTrees.deleteRecursively(edited);
		FileTrees.deleteRecursively(generated);
		FileTrees.write(edited, patched);

		// The mod expects this name and version (PatchBundle.patcher), which catches a wrong patch in the jar.
		PatchSpec spec = PatchSpec.builder()
				.patchName(getPatchName().get())
				.patchVersion("_" + getModVersion().get())
				.baseName(getBaseName().get())
				.build();
		try {
			GeneratedPatch patch = PatchGenerator.generate(GenerateRequest.builder(spec)
					.base(getBaseZip().get().getAsFile().toPath())
					.edited(edited)
					.addOutputDir(generated)
					.debugLog(getLogger()::info)
					.build());
			Files.createDirectories(patchFile.getParent());
			Files.move(patch.getPatchFiles().get(0), patchFile, StandardCopyOption.REPLACE_EXISTING);
		} catch (ShaderPatcherException e) {
			throw new GradleException("Could not generate the patch: " + e.getMessage(), e);
		}
		return Files.size(patchFile);
	}
}
